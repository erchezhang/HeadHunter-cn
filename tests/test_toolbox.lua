-- The toolbox: the website's macro command table as buttons, and the layer (phase)
-- ID card on top (UI/Toolbox.lua).

return function(T, H)
    local function NPC(layer)
        return { name = "Defias Thug", faction = "Horde", isPlayer = false,
            guid = "Creature-0-4613-0-" .. layer .. "-116-0000ABCD" }
    end

    -- The harness stores SetText on the font string itself
    local function Shown(fontString)
        return fontString and fontString.shownText
    end

    T.case("the command table is the website's, with labels where arguments differ", function()
        local ns = H.Boot({ client = "era" })
        T.eq(table.concat(ns.Toolbox.COMMANDS, ","),
            "show,help,options,wanted,outlaw,deaths,posse,bounty,hotspots,duels," ..
            "duelspots,map,tooltip,minimap,claim,catchup,online,layer", "commands")
        T.eq(ns.Toolbox.Label("show"), "/hh", "the plain slash")
        T.eq(ns.Toolbox.Label("outlaw"), "/hh outlaw <name>", "an argument")
        T.eq(ns.Toolbox.Label("layer"), "/hh layer", "a plain command")
        T.noErrors()
    end)

    T.case("layer card: unknown at first, then the ID with zone and age", function()
        local ns = H.Boot({ client = "era" })
        local value, info = ns.Toolbox.LayerLines()
        T.eq(value, "?", "no NPC seen yet")
        T.eq(info, ns.L.LAYER_UNKNOWN, "hint shown")
        H.units.nameplate1 = NPC(777)
        H.Fire("NAME_PLATE_UNIT_ADDED", "nameplate1")
        local zone
        value, info, zone = ns.Toolbox.LayerLines()
        T.eq(value, "777", "the ID")
        T.ok(info:find("777", 1, true) ~= nil, "age line: " .. info)
        T.eq(zone, "Elwynn Forest", "the zone it belongs to")
        T.noErrors()
    end)

    T.case("/hh toolbox opens the window and its buttons run the command", function()
        local ns = H.Boot({ client = "era" })
        H.Slash("toolbox")
        local f = ns.Toolbox:Frame()
        T.ok(f and f:IsShown(), "window shown")
        T.eq(Shown(f.layerValue), "?", "card painted")
        T.eq(f.buttons.status, nil, "the table keeps only the website's commands")
        T.eq(ns.Toolbox.COMMANDS[#ns.Toolbox.COMMANDS], "layer", "ends with the layer lookup")
        -- The layer button runs /hh layer, the same as typing it
        f.buttons.layer:GetScript("OnClick")(f.buttons.layer)
        T.ok(H.Printed("Layer unknown"), "layer from its button")
        T.noErrors()
    end)

    T.case("the window opens and closes; HH_LAYER_CHANGED repaints it", function()
        local ns = H.Boot({ client = "era" })
        H.Slash("toolbox")
        local f = ns.Toolbox:Frame()
        T.eq(Shown(f.layerValue), "?", "unknown first")
        H.units.target = NPC(4321)
        H.Fire("PLAYER_TARGET_CHANGED")
        T.eq(Shown(f.layerValue), "4321", "repainted on HH_LAYER_CHANGED")
        H.Slash("toolbox")
        T.eq(ns.Toolbox:IsShown(), false, "second /hh toolbox closes it")
        T.noErrors()
    end)

    T.case("the Refresh button scans NPCs again", function()
        local ns = H.Boot({ client = "era" })
        H.Slash("toolbox")
        local f = ns.Toolbox:Frame()
        H.units.target = NPC(99)
        f.refresh:GetScript("OnClick")(f.refresh)
        T.eq(Shown(f.layerValue), "99", "rescanned and repainted")
        T.noErrors()
    end)

    T.case("help lists /hh toolbox", function()
        H.Boot({ client = "era" })
        H.Slash("help")
        T.ok(H.Printed("/hh toolbox"), "in the help")
        T.ok(H.Printed("/hh t"), "the short alias too")
        T.noErrors()
    end)

    T.case("/hh t opens and closes the same window", function()
        local ns = H.Boot({ client = "era" })
        H.Slash("t")
        T.ok(ns.Toolbox:IsShown(), "opened by the alias")
        T.ok(ns.Toolbox:Frame() ~= nil, "the same frame")
        H.Slash("t")
        T.eq(ns.Toolbox:IsShown(), false, "closed by the alias again")
        H.Slash("toolbox")
        T.ok(ns.Toolbox:IsShown(), "both commands stay")
        T.noErrors()
    end)

    T.case("the minimap gear button opens the toolbox", function()
        local ns = H.Boot({ client = "era", minimap = true })
        T.ok(ns.MinimapButton:IsShown(), "head shown")
        T.ok(ns.MinimapButton:IsToolboxShown(), "gear shown")
        local gear = _G.HeadHunterToolboxMinimapButton
        T.ok(gear ~= nil, "the gear frame exists")
        gear:GetScript("OnClick")(gear)
        T.ok(ns.Toolbox:IsShown(), "click opens the toolbox")
        gear:GetScript("OnClick")(gear)
        T.eq(ns.Toolbox:IsShown(), false, "click closes it again")
        T.noErrors()
    end)

    T.case("the gear follows /hh minimap and comes back", function()
        local ns = H.Boot({ client = "era", minimap = true })
        H.Slash("minimap")
        T.ok(not ns.MinimapButton:IsShown(), "head hidden")
        T.ok(not ns.MinimapButton:IsToolboxShown(), "gear hidden with it")
        H.Slash("minimap")
        T.ok(ns.MinimapButton:IsShown(), "head back")
        T.ok(ns.MinimapButton:IsToolboxShown(), "gear back")
        T.noErrors()
    end)

    T.case("/hh tool opens and closes the same window", function()
        local ns = H.Boot({ client = "era" })
        H.Slash("tool")
        T.ok(ns.Toolbox:IsShown(), "opened by /hh tool")
        T.ok(ns.Toolbox:Frame() ~= nil, "the same frame")
        H.Slash("tool")
        T.eq(ns.Toolbox:IsShown(), false, "closed by /hh tool again")
        T.noErrors()
    end)

    T.case("/hht opens the toolbox; with arguments it runs like /hh", function()
        local ns = H.Boot({ client = "era" })
        T.eq(_G.SLASH_HEADHUNTER_TOOLBOX1, "/hht", "the top-level command is registered")
        local handler = _G.SlashCmdList.HEADHUNTER_TOOLBOX
        T.ok(handler ~= nil, "the handler exists")
        handler("")
        T.ok(ns.Toolbox:IsShown(), "bare /hht opens the toolbox")
        handler("wanted")
        T.eq(ns.Toolbox:IsShown(), true, "/hht wanted does not toggle the window")
        T.ok(H.Printed("WANTED"), "/hht wanted ran /hh wanted")
        handler("")
        T.eq(ns.Toolbox:IsShown(), false, "bare /hht closes it again")
        T.noErrors()
    end)

    T.case("help names every toolbox entry point", function()
        H.Boot({ client = "era" })
        H.Slash("help")
        T.ok(H.Printed("/hh toolbox"), "full command")
        T.ok(H.Printed("/hh tool"), "the tool alias")
        T.ok(H.Printed("/hh t"), "the short alias")
        T.ok(H.Printed("/hht"), "the top-level alias")
        T.noErrors()
    end)

    T.case("each button shows its description right under it", function()
        local ns = H.Boot({ client = "era" })
        -- The description is the help line without its command part
        T.eq(ns.Toolbox.Desc("wanted"), "Current WANTED list", "wanted")
        T.eq(ns.Toolbox.Desc("help"), "List all commands", "the help button has one too")
        T.eq(ns.Toolbox.Desc("nope"), "", "an unknown command has none")
        H.Slash("toolbox")
        local f = ns.Toolbox:Frame()
        T.ok(f.descs ~= nil, "the description fontstrings exist")
        T.eq(Shown(f.descs.wanted), "Current WANTED list", "shown under the wanted button")
        T.eq(Shown(f.descs.layer), ns.Toolbox.Desc("layer"), "every button got its own")
        T.eq(f.descs.status, nil, "only the table's commands get one")
        T.noErrors()
    end)

    T.case("the outlaw button asks for a name instead of printing the usage", function()
        local ns = H.Boot({ client = "era" })
        H.Slash("toolbox")
        local f = ns.Toolbox:Frame()
        f.buttons.outlaw:GetScript("OnClick")(f.buttons.outlaw)
        T.ok(ns.Toolbox:IsAskShown(), "the name prompt is up")
        T.ok(not H.Printed("Forever names"), "no usage line printed")
        T.noErrors()
    end)

    T.case("SubmitOutlaw runs the command with the typed name", function()
        local ns = H.Boot({ client = "era" })
        H.Slash("toolbox")
        T.ok(ns.Toolbox.SubmitOutlaw("Grim Reaper"), "two-word Forever name accepted")
        T.ok(H.Printed("No kills known for Grim Reaper"), "ran /hh outlaw Grim Reaper")
        T.eq(ns.Toolbox:IsAskShown(), false, "the prompt closed")
        T.eq(ns.Toolbox.SubmitOutlaw("   "), false, "blank input does nothing")
        T.noErrors()
    end)

    T.case("the OK button submits what is in the box; Cancel only closes", function()
        local ns = H.Boot({ client = "era" })
        H.Slash("toolbox")
        ns.Toolbox:AskOutlaw()
        local ask = _G.HeadHunterToolboxAskFrame
        T.ok(ask ~= nil, "the prompt frame exists")
        ask.name:SetText("Thrall")
        ask.ok:GetScript("OnClick")(ask.ok)
        T.ok(H.Printed("No kills known for Thrall"), "OK ran the command")
        T.eq(ns.Toolbox:IsAskShown(), false, "closed after OK")
        ns.Toolbox:AskOutlaw()
        ask.cancel:GetScript("OnClick")(ask.cancel)
        T.eq(ns.Toolbox:IsAskShown(), false, "Cancel closes it too")
        T.noErrors()
    end)

    T.case("the WeChat tag opens the QR code and makes room for it", function()
        local ns = H.Boot({ client = "era" })
        H.Slash("toolbox")
        local f = ns.Toolbox:Frame()
        T.ok(f.qrPanel:IsShown() == false, "the code is hidden at first")
        T.eq(f.height, ns.Toolbox.HEIGHT, "closed height")
        T.eq(f.qrImage.texture, "Interface\\AddOns\\HeadHunter\\Assets\\Textures\\qr", "the picture")
        T.eq(ns.Toolbox:ToggleQR(), true, "opens")
        T.ok(f.qrPanel:IsShown(), "the code is shown")
        T.eq(f.height, ns.Toolbox.HEIGHT_OPEN, "taller while open")
        T.eq(ns.Toolbox:IsQROpen(), true, "state")
        T.eq(ns.Toolbox:ToggleQR(), false, "closes")
        T.ok(f.qrPanel:IsShown() == false, "hidden again")
        T.eq(f.height, ns.Toolbox.HEIGHT, "back to the closed height")
        T.noErrors()
    end)

    T.case("the WeChat tag and its line carry the translated texts", function()
        local ns = H.Boot({ client = "era" })
        H.Slash("toolbox")
        local f = ns.Toolbox:Frame()
        T.eq(f.wechat:GetText(), ns.L.WECHAT_TAG, "the tag label")
        T.eq(f.qrNote.shownText, ns.L.WECHAT_HINT, "the line under the code")
        f.wechat:GetScript("OnClick")(f.wechat)
        T.ok(f.qrPanel:IsShown(), "a click opens the code")
        T.noErrors()
    end)

    T.case("zhCN: the tag and its line are Chinese", function()
        local ns = H.Boot({ client = "era", locale = "zhCN" })
        T.eq(ns.L.WECHAT_TAG, "微信小程序", "tag")
        T.eq(ns.L.WECHAT_HINT, "微信扫码查看小程序，收藏小程序随时关注线上PVP数据。", "line")
        T.noErrors()
    end)
end
